const (
	defaultSGDeletionPollInterval = 2 * time.Second
	defaultSGDeletionTimeout      = 2 * time.Minute

	sgDescription = "[k8s] Shared Backend SecurityGroup for ELB Proxy"
)

const resourceTypeSecurityGroup ec2types.ResourceType = "security-group"

// ResourceType identifies the type of Kubernetes resource using the backend SG.
type ResourceType string

const (
	ResourceTypeGateway ResourceType = "gateway"
)

// BackendSGProvider is responsible for providing backend security groups.
type BackendSGProvider interface {
	// Get returns the backend security group to use.
	Get(ctx context.Context, resourceType ResourceType, activeResources []types.NamespacedName) (string, error)

	// Release cleans up the auto-generated backend SG if necessary.
	Release(ctx context.Context, resourceType ResourceType, inactiveResources []types.NamespacedName) error
}

// PendingDeletionChecker reports whether any gateway keys are still awaiting teardown.
// Used by the backend SG provider to avoid attempting deletion while proxies are still
// being cleaned up (their ENIs still reference the backend SG).
type PendingDeletionChecker interface {
	HasPendingDeletionsExcluding(keys []string) bool
}

type defaultBackendSGProvider struct {
	vpcID       string
	clusterName string
	mutex       sync.Mutex

	backendSG              string
	autoGeneratedSG        string
	ec2Client              services.EC2
	k8sClient              client.Client
	trackingProvider       tracking.Provider
	logger                 logging.Logger
	pendingDeletionChecker PendingDeletionChecker

	// controllerName is the GatewayClass controller name managed by this controller.
	// Used during release to only consider gateways managed by this controller when
	// deciding if the shared backend security group can be deleted.
	controllerName string

	// controllerNamespace scopes the backend SG to this controller instance.
	// In multi-tenant deployments (one controller per namespace), each controller
	// creates and manages its own backend SG, avoiding conflicts on node SG rules.
	controllerNamespace string

	// objectsMap keeps track of whether the backend SG is required for any tracked resources in the cluster.
	// If any entry in the map is true, or there are resources with this controller specific finalizers which
	// haven't been tracked in the map yet, controller doesn't delete the backend SG. If the controller has
	// processed all supported resources and none of them require backend SG, i.e. the values are false in this map
	// controller deletes the backend SG.
	objectsMap sync.Map

	defaultDeletionPollInterval time.Duration
	defaultDeletionTimeout      time.Duration
}

// NewBackendSGProvider constructs a new defaultBackendSGProvider.
func NewBackendSGProvider(
	clusterName string,
	backendSG string,
	vpcID string,
	ec2Client services.EC2,
	k8sClient client.Client,
	trackingProvider tracking.Provider,
	logger logging.Logger,
	controllerName string,
	controllerNamespace string,
	pendingDeletionChecker PendingDeletionChecker,
) *defaultBackendSGProvider {
	return &defaultBackendSGProvider{
		vpcID:                       vpcID,
		clusterName:                 clusterName,
		backendSG:                   backendSG,
		ec2Client:                   ec2Client,
		k8sClient:                   k8sClient,
		trackingProvider:            trackingProvider,
		logger:                      logger,
		controllerName:              controllerName,
		controllerNamespace:         controllerNamespace,
		pendingDeletionChecker:      pendingDeletionChecker,
		mutex:                       sync.Mutex{},
		defaultDeletionPollInterval: defaultSGDeletionPollInterval,
		defaultDeletionTimeout:      defaultSGDeletionTimeout,
	}
}

var _ BackendSGProvider = &defaultBackendSGProvider{}

func (p *defaultBackendSGProvider) Get(ctx context.Context, resourceType ResourceType, activeResources []types.NamespacedName) (string, error) {
	if len(p.backendSG) > 0 {
		return p.backendSG, nil
	}
	// Auto generate Backend Security group, and return the id
	if err := p.allocateBackendSG(ctx, resourceType, activeResources); err != nil {
		p.logger.Error(err, "Failed to auto-create backend SG")
		return "", err
	}
	return p.autoGeneratedSG, nil
}

func (p *defaultBackendSGProvider) Release(ctx context.Context, resourceType ResourceType,
	inactiveResources []types.NamespacedName) error {
	if len(p.backendSG) > 0 {
		return nil
	}
	defer func() {
		for _, res := range inactiveResources {
			p.objectsMap.CompareAndDelete(getObjectKey(resourceType, res), false)
		}
	}()
	p.updateObjectsMap(resourceType, inactiveResources, false)
	p.logger.Info("release backend SG", "inactive", inactiveResources)
	if required, err := p.isBackendSGRequired(ctx, inactiveResources); required || err != nil {
		return err
	}
	return p.releaseSG(ctx)
}

func (p *defaultBackendSGProvider) updateObjectsMap(resourceType ResourceType,
	resources []types.NamespacedName, backendSGRequired bool) {
	for _, res := range resources {
		p.objectsMap.Store(getObjectKey(resourceType, res), backendSGRequired)
	}
}

func (p *defaultBackendSGProvider) isBackendSGRequired(ctx context.Context, currentResources []types.NamespacedName) (bool, error) {
	// If any gateway keys (other than the one currently being torn down) are still
	// awaiting teardown, their proxies may still have ENIs referencing the backend SG.
	// Skip this check when called from releaseSG (currentResources is nil) since
	// the caller already validated through Release().
	if p.pendingDeletionChecker != nil && currentResources != nil {
		excludeKeys := make([]string, 0, len(currentResources))
		for _, res := range currentResources {
			excludeKeys = append(excludeKeys, res.Namespace+"/"+res.Name)
		}
		if p.pendingDeletionChecker.HasPendingDeletionsExcluding(excludeKeys) {
			return true, nil
		}
	}

	var requiredForAny bool
	p.objectsMap.Range(func(_, v interface{}) bool {
		if v.(bool) {
			requiredForAny = true
			return false
		}
		return true
	})
	if requiredForAny {
		return true, nil
	}
	// Check for Gateways with controller finalizers that haven't been tracked yet.
	if required, err := p.checkGatewayListForUnmapped(ctx); required || err != nil {
		return required, err
	}
	return false, nil
}

func (p *defaultBackendSGProvider) checkGatewayListForUnmapped(ctx context.Context) (bool, error) {
	gwList := &gwapiv1.GatewayList{}
	if err := p.k8sClient.List(ctx, gwList); err != nil {
		return true, fmt.Errorf("unable to list gateways: %w", err)
	}

	// Cache GatewayClass lookups to avoid repeated API calls.
	gcCache := make(map[string]bool)

	for _, gw := range gwList.Items {
		className := string(gw.Spec.GatewayClassName)
		managed, cached := gcCache[className]
		if !cached {
			gc := &gwapiv1.GatewayClass{}
			if err := p.k8sClient.Get(ctx, client.ObjectKey{Name: className}, gc); err != nil {
				if !apierrors.IsNotFound(err) {
					// Transient error - assume the gateway might be managed to avoid releasing the shared backend security group.
					p.logger.Error(err, "failed to get GatewayClass", "name", className)
					return true, nil
				}
				gcCache[className] = false
				continue
			}
			managed = string(gc.Spec.ControllerName) == p.controllerName
			gcCache[className] = managed
		}
		if !managed {
			continue
		}
		if !p.existsInObjectMap(ResourceTypeGateway, types.NamespacedName{
			Namespace: gw.Namespace,
			Name:      gw.Name,
		}) {
			return true, nil
		}
	}
	return false, nil
}

func (p *defaultBackendSGProvider) existsInObjectMap(resourceType ResourceType, resource types.NamespacedName) bool {
	_, exists := p.objectsMap.Load(getObjectKey(resourceType, resource))
	return exists
}

func (p *defaultBackendSGProvider) allocateBackendSG(ctx context.Context, resourceType ResourceType, activeResources []types.NamespacedName) error {
	p.mutex.Lock()
	defer p.mutex.Unlock()

	p.updateObjectsMap(resourceType, activeResources, true)
	if len(p.autoGeneratedSG) > 0 {
		return nil
	}

	sgName := p.getBackendSGName()
	sg, err := p.getBackendSGFromEC2(ctx, p.vpcID)
	if err != nil {
		return err
	}
	if sg != nil {
		sgID := aws.ToString(sg.GroupId)
		p.logger.Info("existing backend SG found", "id", sgID)
		p.autoGeneratedSG = sgID
		if err = p.reconcileTags(ctx, *sg); err != nil {
			p.logger.Error(err, "failed to synchronize tags of existing securityGroup", "id", sgID)
			return err
		}
		return nil
	}

	createReq := &ec2.CreateSecurityGroupInput{
		VpcId:       aws.String(p.vpcID),
		GroupName:   aws.String(sgName),
		Description: aws.String(sgDescription),
		TagSpecifications: []ec2types.TagSpecification{
			{
				ResourceType: resourceTypeSecurityGroup,
				Tags:         p.buildBackendSGSDKTags(),
			},
		},
	}
	p.logger.Info("creating securityGroup", "name", sgName)
	resp, err := p.ec2Client.CreateSecurityGroupWithContext(ctx, createReq)
	if err != nil {
		return err
	}
	p.logger.Info("created securityGroup", "name", sgName, "id", aws.ToString(resp.GroupId))
	p.autoGeneratedSG = aws.ToString(resp.GroupId)
	return nil
}

func (p *defaultBackendSGProvider) reconcileTags(ctx context.Context, sg ec2types.SecurityGroup) error {
	desiredTags := p.buildBackendSGTagsMap()
	currentTags := make(map[string]string)
	for _, tag := range sg.Tags {
		currentTags[aws.ToString(tag.Key)] = aws.ToString(tag.Value)
	}

	tagsToUpdate, tagsToRemove := algorithm.DiffStringMap(desiredTags, currentTags)
	sgID := aws.ToString(sg.GroupId)

	if len(tagsToUpdate) > 0 {
		sdkTags := make([]ec2types.Tag, 0, len(tagsToUpdate))
		for _, key := range sets.StringKeySet(tagsToUpdate).List() {
			sdkTags = append(sdkTags, ec2types.Tag{
				Key:   aws.String(key),
				Value: aws.String(tagsToUpdate[key]),
			})
		}
		req := &ec2.CreateTagsInput{
			Resources: []string{sgID},
			Tags:      sdkTags,
		}
		p.logger.Info("adding resource tags", "resourceID", sgID, "change", tagsToUpdate)
		if _, err := p.ec2Client.CreateTagsWithContext(ctx, req); err != nil {
			return err
		}
		p.logger.Info("added resource tags", "resourceID", sgID)
	}

	if len(tagsToRemove) > 0 {
		sdkTags := make([]ec2types.Tag, 0, len(tagsToRemove))
		for _, key := range sets.StringKeySet(tagsToRemove).List() {
			sdkTags = append(sdkTags, ec2types.Tag{
				Key:   aws.String(key),
				Value: aws.String(tagsToRemove[key]),
			})
		}
		req := &ec2.DeleteTagsInput{
			Resources: []string{sgID},
			Tags:      sdkTags,
		}
		p.logger.Info("removing resource tags", "resourceID", sgID, "change", tagsToRemove)
		if _, err := p.ec2Client.DeleteTagsWithContext(ctx, req); err != nil {
			return err
		}
		p.logger.Info("removed resource tags", "resourceID", sgID)
	}

	return nil
}

func (p *defaultBackendSGProvider) buildBackendSGTagsMap() map[string]string {
	tags := p.trackingProvider.BuildClusterTags(tracking.ResourceIDBackendSecurityGroup)
	tags[tracking.TagKeyControllerNS] = p.controllerNamespace
	return tags
}

func (p *defaultBackendSGProvider) buildBackendSGSDKTags() []ec2types.Tag {
	tags := p.buildBackendSGTagsMap()
	sdkTags := make([]ec2types.Tag, 0, len(tags))
	for _, key := range sets.StringKeySet(tags).List() {
		sdkTags = append(sdkTags, ec2types.Tag{
			Key:   aws.String(key),
			Value: aws.String(tags[key]),
		})
	}
	return sdkTags
}

func (p *defaultBackendSGProvider) getBackendSGFromEC2(ctx context.Context, vpcID string) (*ec2types.SecurityGroup, error) {
	req := &ec2.DescribeSecurityGroupsInput{
		Filters: []ec2types.Filter{
			{
				Name:   aws.String("vpc-id"),
				Values: []string{vpcID},
			},
			{
				Name:   aws.String(fmt.Sprintf("tag:%v", tracking.TagKeyCluster)),
				Values: []string{p.clusterName},
			},
			{
				Name:   aws.String(fmt.Sprintf("tag:%v", tracking.TagKeyResourceType)),
				Values: []string{tracking.ResourceIDBackendSecurityGroup},
			},
			{
				Name:   aws.String(fmt.Sprintf("tag:%v", tracking.TagKeyControllerNS)),
				Values: []string{p.controllerNamespace},
			},
		},
	}
	p.logger.Info("querying existing backend SG", "vpc-id", vpcID)
	sgs, err := p.ec2Client.DescribeSecurityGroupsAsList(ctx, req)
	if err != nil && !isEC2SecurityGroupNotFoundError(err) {
		return nil, err
	}
	if len(sgs) > 0 {
		return &sgs[0], nil
	}
	return nil, nil
}

func (p *defaultBackendSGProvider) releaseSG(ctx context.Context) error {
	p.mutex.Lock()
	defer p.mutex.Unlock()

	if len(p.autoGeneratedSG) == 0 {
		return nil
	}
	if required, err := p.isBackendSGRequired(ctx, nil); required || err != nil {
		p.logger.Info("releaseSG ignore delete", "required", required, "err", err)
		return err
	}

	req := &ec2.DeleteSecurityGroupInput{
		GroupId: aws.String(p.autoGeneratedSG),
	}
	if err := runtime.RetryImmediateOnError(p.defaultDeletionPollInterval, p.defaultDeletionTimeout, isSecurityGroupDependencyViolationError, func() error {
		_, err := p.ec2Client.DeleteSecurityGroupWithContext(ctx, req)
		return err
	}); err != nil {
		return fmt.Errorf("failed to delete securityGroup: %w", err)
	}
	p.logger.Info("deleted backend securityGroup", "ID", p.autoGeneratedSG)
	p.autoGeneratedSG = ""
	return nil
}

var invalidSGNamePattern = regexp.MustCompile("[[:^alnum:]]")

func (p *defaultBackendSGProvider) getBackendSGName() string {
	sgNameHash := sha256.New()
	_, _ = sgNameHash.Write([]byte(p.clusterName))
	_, _ = sgNameHash.Write([]byte("/"))
	_, _ = sgNameHash.Write([]byte(p.controllerNamespace))
	sgHash := hex.EncodeToString(sgNameHash.Sum(nil))
	sanitizedClusterName := invalidSGNamePattern.ReplaceAllString(p.clusterName, "")
	return fmt.Sprintf("elbproxy-backend-%.24s-%.10s", sanitizedClusterName, sgHash)
}

func isSecurityGroupDependencyViolationError(err error) bool {
	var apiErr smithy.APIError
	if errors.As(err, &apiErr) {
		return apiErr.ErrorCode() == "DependencyViolation"
	}
	return false
}

func isEC2SecurityGroupNotFoundError(err error) bool {
	var apiErr smithy.APIError
	if errors.As(err, &apiErr) {
		return apiErr.ErrorCode() == "InvalidGroup.NotFound"
	}
	return false
}

func getObjectKey(resourceType ResourceType, resource types.NamespacedName) string {
	return string(resourceType) + "/" + resource.String()
}
